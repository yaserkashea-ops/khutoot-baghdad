  /// Option label to pin a freely typed place name.
  static String pinTypedLabel(String typed) => 'ثبّت «${typed.trim()}»';

  static bool isPinTypedOption(String option) =>
      option.startsWith('ثبّت «') && option.endsWith('»');

  static String? extractPinnedText(String option) {
    if (!isPinTypedOption(option)) return null;
    return option.substring('ثبّت «'.length, option.length - 1);
  }

  /// تطبيع عربي خفيف للمطابقة: أ/إ/آ→ا، ة→ه، ى→ي، وحذف أداة التعريف في البداية.
  static String normalizeArabic(String input) {
    var s = input.trim();
    s = s.replaceAll(RegExp('[أإآ]'), 'ا');
    s = s.replaceAll('ة', 'ه');
    s = s.replaceAll('ى', 'ي');
    s = s.replaceAll('ؤ', 'و');
    s = s.replaceAll('ئ', 'ي');
    if (s.startsWith('ال')) {
      s = s.substring(2);
    }
    return s;
  }

  static bool matchesQuery(String option, String query) {
    final q = query.trim();
    if (q.isEmpty) return true;
    if (option.contains(q)) return true;
    return normalizeArabic(option).contains(normalizeArabic(q));
  }

  static List<String> prioritize(
    Iterable<String> all, {
    List<String> core = coreAreas,
  }) {
    final remaining = all.toSet();
    final head = <String>[];
    for (final item in core) {
      if (remaining.remove(item)) head.add(item);
    }
    final tail = remaining.toList()..sort();
    return [...head, ...tail];
  }

  static List<String> match(String query, Iterable<String> options) {
    final prioritized = prioritize(options);
    final q = query.trim();
    if (q.isEmpty) return prioritized;
    return prioritized.where((o) => matchesQuery(o, q)).toList();
  }

  static List<String> areasWith(Iterable<String> extra) =>
      prioritize({...areas, ...extra});

  static List<String> destinationsWith(Iterable<String> extra) =>
      prioritize({...areas, ...institutions, ...extra});
}
